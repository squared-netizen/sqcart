#!/usr/bin/env python3
# v3/tools/gen_casefold.py: write v3/src/casefold.inc, the table of Unicode
# full case folding (CaseFolding.txt, statuses C and F) the reader uses to
# find paths that collide (format 3.0 §4.1). From this Python's
# str.casefold(), so the Unicode version is Python's: run it with a newer
# Python when Unicode moves, and commit the result.
import sys
import unicodedata
from pathlib import Path

rows = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    folded = chr(cp).casefold()
    if folded != chr(cp):
        rows.append((cp, [ord(c) for c in folded] + [0] * (3 - len(folded))))
out = [
    "// Generated by v3/tools/gen_casefold.py from Python %s's str.casefold()" % sys.version.split()[0],
    "// (Unicode %s): Unicode full case folding, CaseFolding.txt statuses C and F."
    % unicodedata.unidata_version,
    "// One row a code point that folds to something else: the code point, then",
    "// up to three it folds to (0: none). Sorted, for binary search.",
    "{",
]
out += ["    {0x%04X, {0x%04X, 0x%04X, 0x%04X}}," % (cp, *to) for cp, to in rows]
out.append("}")
Path(__file__).resolve().parent.parent.joinpath("src", "casefold.inc").write_text("\n".join(out) + "\n")
print("%d code points" % len(rows))
