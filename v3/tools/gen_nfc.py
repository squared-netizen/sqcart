#!/usr/bin/env python3
# v3/tools/gen_nfc.py: write v3/src/nfc.inc, the tables the reader and
# writer normalize paths to NFC with (format 3.0 §4.1, §6.1): canonical
# combining classes, full canonical decompositions, and the pairs that
# compose (exclusions already left out). From this Python's unicodedata, so
# the Unicode version is Python's, as casefold.inc's is: run it with a newer
# Python when Unicode moves, and commit the result. Hangul is algorithmic and
# not in the tables.
import sys
import unicodedata
from pathlib import Path


def full_decomposition(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):  # none, or a compatibility one
        return None
    out = []
    for part in d.split():
        sub = full_decomposition(int(part, 16))
        out += sub if sub else [int(part, 16)]
    return out


def hangul(cp):
    return 0xAC00 <= cp <= 0xD7A3


ccc, decomp, compose = [], [], []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF or hangul(cp):
        continue
    c = unicodedata.combining(chr(cp))
    if c:
        ccc.append((cp, c))
    full = full_decomposition(cp)
    if full:
        decomp.append((cp, full))
        # A pair that composes: a primary composite whose decomposition is
        # two code points and which NFC gives back (exclusions do not).
        raw = unicodedata.decomposition(chr(cp)).split()
        if len(raw) == 2 and unicodedata.normalize("NFC", chr(int(raw[0], 16)) + chr(int(raw[1], 16))) == chr(cp):
            compose.append((int(raw[0], 16), int(raw[1], 16), cp))

width = max(len(d) for _, d in decomp)
compose.sort()
out = [
    "// Generated by v3/tools/gen_nfc.py from Python %s's unicodedata (Unicode %s):"
    % (sys.version.split()[0], unicodedata.unidata_version),
    "// canonical combining classes, full canonical decompositions (Hangul is",
    "// algorithmic, not here), and the pairs that compose. Sorted, for binary search.",
    "constexpr std::size_t nfc_decomposition_width = %d;" % width,
    "constexpr std::pair<char32_t, std::uint8_t> nfc_ccc[] = {",
]
out += ["    {0x%04X, %d}," % row for row in ccc]
out.append("};")
out.append("constexpr std::pair<char32_t, std::array<char32_t, %d>> nfc_decompositions[] = {" % width)
out += ["    {0x%04X, {%s}}," % (cp, ", ".join("0x%04X" % x for x in d + [0] * (width - len(d)))) for cp, d in decomp]
out.append("};")
out.append("constexpr std::array<char32_t, 3> nfc_compositions[] = {")
out += ["    {0x%04X, 0x%04X, 0x%04X}," % row for row in compose]
out.append("};")
Path(__file__).resolve().parent.parent.joinpath("src", "nfc.inc").write_text("\n".join(out) + "\n")
print("%d classes, %d decompositions (width %d), %d compositions" % (len(ccc), len(decomp), width, len(compose)))
